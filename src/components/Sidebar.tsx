export default function Sidebar() {
  const pathname = usePathname();
  const { theme, setTheme } = useTheme();
  const { user, isSystemAdmin, canAccess } = useAuth();

  const visibleNav = nav
    .map((item) => {
      if (item.href === "/") return item;
      if (item.href === "/admins") return isSystemAdmin ? item : null;
      if (item.children) {
        const children = item.children.filter((c) => canAccess("/" + (c.href.split("/")[1] || "")));
        return children.length > 0 ? { ...item, children } : null;
      }
      const topSegment = "/" + (item.href.split("/")[1] || "");
      return canAccess(topSegment) ? item : null;
    })
    .filter((item): item is NavItem => item !== null);

  return (
    <aside className="w-[200px] shrink-0 h-full flex flex-col border-r border-border-primary bg-bg-sidebar">
      {/* Brand */}
      <div className="h-12 flex items-center px-4 border-b border-border-primary">
        <div className="flex items-center gap-2">
          <div className="w-5 h-5 rounded-full bg-accent flex items-center justify-center">
            <span className="text-[9px] font-bold text-white">S</span>
          </div>
          <span className="text-sm font-semibold text-text-primary">Slowave 1.0</span>
          <span className="text-[10px] px-1.5 py-0.5 rounded-full bg-bg-tertiary text-text-tertiary font-medium">Admin</span>
        </div>
      </div>

      {/* Navigation */}
      <nav className="flex-1 px-2 py-3 space-y-0.5 overflow-y-auto">
        {visibleNav.map((item) => {
          if (item.children) {
            return (
              <div key={item.href}>
                <div className="flex items-center gap-2.5 px-2.5 py-1.5 text-[13px] text-text-secondary">
                  {item.icon}
                  {item.label}
                </div>
                <div className="space-y-0.5">
                  {item.children.map((child) => {
                    const childActive =
                      child.href === item.href
                        ? pathname === child.href
                        : pathname.startsWith(child.href);
                    return (
                      <Link
                        key={child.href}
                        href={child.href}
                        className={`flex items-center gap-2.5 pl-[38px] pr-2.5 py-1.5 rounded-md text-[13px] transition-colors ${
                          childActive
                            ? "bg-bg-active text-text-primary font-medium"
                            : "text-text-secondary hover:bg-bg-hover hover:text-text-primary"
                        }`}
                      >
                        {child.label}
                      </Link>
                    );
                  })}
                </div>
              </div>
            );
          }
          const moreSpecific = visibleNav.some(
            (n) => n.href !== item.href && n.href.startsWith(item.href + "/") && pathname.startsWith(n.href)
          );
          const active =
            item.href === "/"
              ? pathname === "/"
              : pathname.startsWith(item.href) && !moreSpecific;
          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex items-center gap-2.5 px-2.5 py-1.5 rounded-md text-[13px] transition-colors ${
                active
                  ? "bg-bg-active text-text-primary font-medium"
                  : "text-text-secondary hover:bg-bg-hover hover:text-text-primary"
              }`}
            >
              {item.icon}
              {item.label}
            </Link>
          );
        })}
      </nav>

      {/* Theme Toggle */}
      <div className="px-3 py-3 border-t border-border-primary">
        <div className="flex items-center gap-0.5 rounded-lg bg-bg-tertiary p-0.5">
          <button
            onClick={() => setTheme("light")}
            className={`flex-1 flex items-center justify-center rounded-md py-1.5 transition-colors ${
              theme === "light"
                ? "bg-bg-card text-text-primary shadow-sm"
                : "text-text-muted hover:text-text-secondary"
            }`}
            title="Light"
          >
            <SunIcon />
          </button>
          <button
            onClick={() => setTheme("dark")}
            className={`flex-1 flex items-center justify-center rounded-md py-1.5 transition-colors ${
              theme === "dark"
                ? "bg-bg-card text-text-primary shadow-sm"
                : "text-text-muted hover:text-text-secondary"
            }`}
            title="Dark"
          >
            <MoonIcon />
          </button>
          <button
            onClick={() => setTheme("system")}
            className={`flex-1 flex items-center justify-center rounded-md py-1.5 transition-colors ${
              theme === "system"
                ? "bg-bg-card text-text-primary shadow-sm"
                : "text-text-muted hover:text-text-secondary"
            }`}
            title="System"
          >
            <MonitorIcon />
          </button>
        </div>
      </div>
    </aside>
  );
}
